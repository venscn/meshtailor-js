import {mkdir,writeFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {join} from 'node:path';
import {compileCore} from './lib/compiled-core.mjs';
import {writeASCII,writeBinary} from './lib/fbx-fixture.mjs';
const compiled=await compileCore();
try{
  const core=await compiled.load('packages/mesh-core/src/index.js');
  const models=join(compiled.root,'examples/complex'),fixtures=join(compiled.root,'apps/studio/public/assets/fixtures');
  await mkdir(models,{recursive:true});await mkdir(fixtures,{recursive:true});
  const manifest={origin:'Generated by MeshTailor-JS, not downloaded assets',license:'MIT',meshes:[],fbxFixtures:[]};
  for(const item of core.COMPLEX_EXAMPLES){
    const mesh=core.makeComplexExample(item.id,'medium'),data=core.meshToOBJ(mesh),file=item.id+'.obj';await writeFile(join(models,file),data);
    manifest.meshes.push({id:item.id,file:'examples/complex/'+file,vertices:mesh.positions.length,triangles:mesh.faces.length,sha256:createHash('sha256').update(data).digest('hex')});
  }
  const garment=core.makePleatedGarment('low');
  for(const [kind,data] of [['ascii',writeASCII(garment)],['binary',writeBinary(garment)]]){
    const file=`garment-${kind}.fbx`;await writeFile(join(fixtures,file),data);
    manifest.fbxFixtures.push({file:'apps/studio/public/assets/fixtures/'+file,format:kind,fbxVersion:7400,vertices:garment.positions.length,triangles:garment.faces.length,sha256:createHash('sha256').update(data).digest('hex')});
  }
  await writeFile(join(compiled.root,'examples/manifest.json'),JSON.stringify(manifest,null,2)+'\n');
  console.log(JSON.stringify(manifest,null,2));
}finally{await compiled.cleanup();}
