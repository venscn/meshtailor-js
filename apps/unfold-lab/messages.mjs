/** Format declared offline/shared keys without reading or mutating app state. */
export function offlineMessage(key,values=[]){
  if(!Object.hasOwn(offlineCopy,key))return message(key,values);
  const text=displayPreferences.getSnapshot().locale==='en'?offlineCopy[key]:key;
  return text.replace(/\{(\d+)\}/g,(placeholder,index)=>values[Number(index)]===undefined?placeholder:String(values[Number(index)]));
}

