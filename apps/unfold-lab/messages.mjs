/** Binding only opt-in keys preserves nested inputs, IDs and machine values.
 * Rebinding changes presentation; it never dispatches events or solves a mesh. */
export function bindOfflineMessages(root=document){
  for(const element of root.querySelectorAll('[data-message]'))element.textContent=offlineMessage(element.dataset.message);
  for(const element of root.querySelectorAll('[data-message-aria]'))element.setAttribute('aria-label',offlineMessage(element.dataset.messageAria));
  for(const element of root.querySelectorAll('[data-message-placeholder]'))element.setAttribute('placeholder',offlineMessage(element.dataset.messagePlaceholder));
}
